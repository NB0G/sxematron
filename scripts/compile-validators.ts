/** Precompile JSON Schema at build time: production/browser never use eval. */
import AjvModule from 'ajv';
import standaloneModule from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { componentSchema, schematicSchema } from '../packages/core/src/schemas.js';

const Ajv = AjvModule as unknown as typeof import('ajv').Ajv;
const standaloneCode = standaloneModule as unknown as typeof import('ajv/dist/standalone/index.js').default;
const ajv = new Ajv({ allErrors:true, strict:true, strictNumbers:true, code:{source:true,esm:true} });
ajv.addSchema(componentSchema);
ajv.addSchema(schematicSchema);
const source = standaloneCode(ajv, {
  validateComponentJson:componentSchema.$id,
  validateSchematicJson:schematicSchema.$id
});
// Ajv standalone may reference tiny CommonJS runtime helpers. Bundle those
// helpers into the source so neither browser require() nor runtime Ajv remain.
const result = await build({
  stdin:{contents:source,resolveDir:process.cwd(),sourcefile:'ajv-standalone.js',loader:'js'},
  bundle:true,platform:'browser',format:'esm',target:'es2022',write:false,
  legalComments:'none',banner:{js:'// @ts-nocheck\n// Generated by scripts/compile-validators.ts. Do not edit; edit schemas.ts instead.'}
});
const output=result.outputFiles[0].text;
if (/\bnew\s+Function\s*\(|\beval\s*\(/.test(output)) throw new Error('Сгенерированный валидатор содержит динамическое выполнение кода.');
writeFileSync(path.resolve('packages/core/src/generated-validators.ts'),output);
console.log('Generated standalone validators: '+output.length+' bytes; runtime eval disabled.');
